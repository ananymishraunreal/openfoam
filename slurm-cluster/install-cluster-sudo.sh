#!/usr/bin/env bash
# install-cluster-sudo.sh — single-node Slurm bootstrap on Omarchy/Arch.
# Run as root:  sudo bash install-cluster-sudo.sh
# Handles: pacman packages (munge, openmpi, build deps), building SchedMD
# Slurm from the official tarball into /usr/local, config files, systemd
# services, and a first smoke check.

set -eo pipefail

echo "=== [1/8] packages ==="
pacman -Sy --needed --noconfirm munge openmpi json-c glib2 curl base-devel

echo "=== [2/8] slurm user + dirs ==="
getent passwd slurm >/dev/null 2>&1 || useradd -r -M -d /var/lib/slurm -s /usr/sbin/nologin slurm
mkdir -p /var/spool/slurmd /var/spool/slurmctld /var/lib/slurm /var/log/slurm /run/slurm /etc/slurm
chown -R slurm: /var/spool/slurmctld /var/lib/slurm /var/log/slurm /run/slurm
# /var/spool/slurmd stays root-owned (slurmd runs as root)

echo "=== [3/8] host resolution ==="
HN=$(hostname)
grep -q "127.0.1.1 $HN" /etc/hosts || echo "127.0.1.1 $HN" >> /etc/hosts

echo "=== [4/8] munge key ==="
MUNGEKEY=/etc/munge/munge.key
if [ ! -s "$MUNGEKEY" ]; then
    dd if=/dev/urandom bs=1024 count=1 > "$MUNGEKEY"
fi
chmod 600 "$MUNGEKEY"
chown -R munge:munge /etc/munge
chmod 700 /etc/munge

echo "=== [5/8] build Slurm from SchedMD tarball ==="
mkdir -p /usr/local/src
cd /usr/local/src
SLURM_SRC=""
for V in 25.05.2 24.11.6 23.11.11; do
    T="slurm-$V.tar.bz2"
    if curl -fsSL -o "$T" "https://download.schedmd.com/slurm/$T"; then
        rm -rf "slurm-$V"; tar -xjf "$T"
        SLURM_SRC="/usr/local/src/slurm-$V"
        break
    fi
done
[ -n "$SLURM_SRC" ] || { echo "could not fetch any Slurm tarball" >&2; exit 1; }
cd "$SLURM_SRC"
./configure --prefix=/usr/local \
    --with-munge=/usr \
    --without-pam \
    --without-gpu \
    --with-hdf5=no \
    LDFLAGS="-Wl,-rpath,/usr/local/lib"
make -j"$(nproc)"
make install

echo 'ldconfig snip'
echo "/usr/local/lib" > /etc/ld.so.conf.d/slurm.conf
ldconfig

echo "=== [6/8] slurm.conf ==="
HN=$(hostname)
cat > /etc/slurm/slurm.conf <<EOF
# single-node Slurm config generated by Sluice fixture setup
ClusterName=sluice
SlurmctldHost=$HN
AuthType=auth/munge
MpiDefault=none
ProctrackType=proctrack/pgid
ReturnToService=2
SchedulerType=sched/builtin
SelectType=select/cons_tres
SelectTypeParameters=CR_Core
SlurmctldPort=6817
SlurmdPort=6818
StateSaveLocation=/var/spool/slurmctld
SlurmdSpoolDir=/var/spool/slurmd
SlurmctldPidFile=/run/slurm/slurmctld.pid
SlurmdPidFile=/run/slurm/slurmd.pid
SlurmUser=slurm
TaskPlugin=none
InactiveLimit=0
KillWait=30
MinJobAge=300
SlurmctldTimeout=120
SlurmdTimeout=300
MaxJobCount=1000

NodeName=$HN CPUs=16 RealMemory=15000 Sockets=1 State=UNKNOWN
PartitionName=all Nodes=ALL Default=YES MaxTime=INFINITE State=UP
EOF

echo "=== [7/8] systemd units ==="
cat > /etc/systemd/system/slurmctld.service <<EOF
[Unit]
Description=Slurm controller daemon
After=network.target munge.service
[Service]
Type=simple
User=slurm
Group=slurm
ExecStart=/usr/local/sbin/slurmctld -D
Restart=always
[Install]
WantedBy=multi-user.target
EOF
cat > /etc/systemd/system/slurmd.service <<EOF
[Unit]
Description=Slurm node daemon
After=network.target munge.service
[Service]
Type=simple
ExecStart=/usr/local/sbin/slurmd -D
Restart=always
[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable --now munge
systemctl enable --now slurmctld
systemctl enable --now slurmd
sleep 3
systemctl --no-pager --full status munge slurmctld slurmd | head -40 || true

echo "=== [8/8] smoke ==="
/usr/local/bin/sinfo
/usr/local/bin/srun -n1 hostname
echo "install-cluster-sudo.sh: OK"
